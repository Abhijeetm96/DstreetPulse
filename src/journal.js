/**
 * Trade Journal and Performance Analytics Module
 * 
 * Persistent ledger backed by SQLite (node:sqlite)
 * Features:
 * - Trade lifecycle tracking (PROPOSED, PENDING_APPROVAL, ACTIVE, CLOSED, CANCELLED)
 * - Fills, modifications, exits, and exact fee logging
 * - Realized vs Unrealized P&L reconciliation with portfolio holdings
 * - Analytics: Win Rate, Profit Factor, Expectancy, Max Drawdown, Holding Period
 */

import { DatabaseSync } from 'node:sqlite';
import { existsSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

export class TradeJournal {
  /**
   * @param {string} dbPath - File path to SQLite database
   */
  constructor(dbPath = './data/trading_journal.db') {
    this.dbPath = dbPath;
    const dir = dirname(dbPath);
    if (!existsSync(dir)) {
      mkdirSync(dir, { recursive: true });
    }
    this.db = new DatabaseSync(dbPath);
    this.initTables();
  }

  /**
   * Initialize schema
   */
  initTables() {
    this.db.exec(`
      CREATE TABLE IF NOT EXISTS trades (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        symbol TEXT NOT NULL,
        exchange TEXT DEFAULT 'NSE',
        setup_type TEXT,
        status TEXT NOT NULL, -- PROPOSED, PENDING_APPROVAL, ACTIVE, CLOSED, CANCELLED
        entry_trigger TEXT,
        entry_price REAL,
        stop_loss REAL,
        target_price REAL,
        quantity INTEGER,
        planned_risk_inr REAL,
        capital_inr REAL,
        entry_timestamp TEXT,
        exit_timestamp TEXT,
        exit_price REAL,
        exit_reason TEXT,
        holding_days INTEGER DEFAULT 0,
        realized_pnl_inr REAL DEFAULT 0.0,
        total_fees_inr REAL DEFAULT 0.0,
        net_pnl_inr REAL DEFAULT 0.0,
        notes TEXT,
        is_paper INTEGER DEFAULT 1,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP
      );

      CREATE TABLE IF NOT EXISTS trade_events (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        trade_id INTEGER,
        event_type TEXT NOT NULL, -- PROPOSED, APPROVED, FILLED, STOP_MODIFIED, EXIT_FILLED
        price REAL,
        quantity INTEGER,
        fees REAL,
        notes TEXT,
        timestamp TEXT DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY(trade_id) REFERENCES trades(id)
      );

      CREATE TABLE IF NOT EXISTS reconciliations (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        timestamp TEXT DEFAULT CURRENT_TIMESTAMP,
        portfolio_holdings_count INTEGER,
        journal_active_count INTEGER,
        discrepancies TEXT,
        status TEXT
      );
    `);
  }

  /**
   * Record a newly proposed research trade
   * @param {Object} tradeData 
   * @returns {number} trade id
   */
  recordProposedTrade(tradeData) {
    const stmt = this.db.prepare(`
      INSERT INTO trades (
        symbol, exchange, setup_type, status, entry_trigger,
        entry_price, stop_loss, target_price, quantity,
        planned_risk_inr, capital_inr, notes, is_paper
      ) VALUES (
        ?, ?, ?, 'PROPOSED', ?,
        ?, ?, ?, ?,
        ?, ?, ?, ?
      )
    `);

    const result = stmt.run(
      tradeData.symbol ?? 'UNKNOWN',
      tradeData.exchange ?? 'NSE',
      tradeData.setupType ?? 'Breakout',
      tradeData.entryTrigger ?? 'Close confirmation',
      tradeData.entryPrice ?? null,
      tradeData.stopLoss ?? null,
      tradeData.targetPrice ?? null,
      tradeData.quantity ?? null,
      tradeData.plannedRiskInr ?? null,
      tradeData.capitalInr ?? null,
      tradeData.notes ?? '',
      tradeData.isPaper ? 1 : 0
    );

    const tradeId = Number(result.lastInsertRowid);

    this.logEvent(tradeId, 'PROPOSED', tradeData.entryPrice, tradeData.quantity, 0, 'Candidate generated by research scanner');
    return tradeId;
  }

  /**
   * Log an event in trade history
   */
  logEvent(tradeId, eventType, price, quantity, fees = 0, notes = '') {
    const stmt = this.db.prepare(`
      INSERT INTO trade_events (trade_id, event_type, price, quantity, fees, notes)
      VALUES (?, ?, ?, ?, ?, ?)
    `);
    stmt.run(tradeId, eventType, price, quantity, fees, notes);
  }

  /**
   * Approve trade for paper or live execution
   */
  approveTrade(tradeId, operatorNotes = '') {
    const stmt = this.db.prepare(`
      UPDATE trades SET status = 'PENDING_APPROVAL', notes = notes || ' | Approved: ' || ?
      WHERE id = ?
    `);
    stmt.run(operatorNotes, tradeId);
    this.logEvent(tradeId, 'APPROVED', null, null, 0, operatorNotes);
  }

  /**
   * Mark a trade as filled (active)
   */
  fillTrade(tradeId, fillPrice, quantity, entryTime, fees = 0) {
    const stmt = this.db.prepare(`
      UPDATE trades 
      SET status = 'ACTIVE', entry_price = ?, quantity = ?, entry_timestamp = ?, total_fees_inr = ?
      WHERE id = ?
    `);
    stmt.run(fillPrice, quantity, entryTime, fees, tradeId);
    this.logEvent(tradeId, 'FILLED', fillPrice, quantity, fees, 'Order executed');
  }

  /**
   * Close a trade and compute realized P&L
   */
  closeTrade(tradeId, exitPrice, exitTime, exitReason, additionalFees = 0) {
    const trade = this.getTrade(tradeId);
    if (!trade) throw new Error(`Trade #${tradeId} not found`);

    const grossPnl = (exitPrice - trade.entry_price) * trade.quantity;
    const totalFees = trade.total_fees_inr + additionalFees;
    const netPnl = grossPnl - totalFees;

    // Calculate holding days
    const entryDate = new Date(trade.entry_timestamp || trade.created_at);
    const exitDate = new Date(exitTime);
    const diffMs = Math.max(0, exitDate.getTime() - entryDate.getTime());
    const holdingDays = Math.ceil(diffMs / (1000 * 60 * 60 * 24));

    const stmt = this.db.prepare(`
      UPDATE trades 
      SET status = 'CLOSED',
          exit_price = ?,
          exit_timestamp = ?,
          exit_reason = ?,
          holding_days = ?,
          realized_pnl_inr = ?,
          total_fees_inr = ?,
          net_pnl_inr = ?
      WHERE id = ?
    `);

    stmt.run(exitPrice, exitTime, exitReason, holdingDays, grossPnl, totalFees, netPnl, tradeId);
    this.logEvent(tradeId, 'EXIT_FILLED', exitPrice, trade.quantity, additionalFees, `Closed: ${exitReason}`);

    return { tradeId, grossPnl, totalFees, netPnl, holdingDays };
  }

  /**
   * Get single trade
   */
  getTrade(tradeId) {
    const stmt = this.db.prepare('SELECT * FROM trades WHERE id = ?');
    return stmt.get(tradeId);
  }

  /**
   * Get all active positions
   */
  getActivePositions() {
    const stmt = this.db.prepare("SELECT * FROM trades WHERE status = 'ACTIVE'");
    return stmt.all();
  }

  /**
   * Get all closed trades
   */
  getClosedTrades() {
    const stmt = this.db.prepare("SELECT * FROM trades WHERE status = 'CLOSED'");
    return stmt.all();
  }

  /**
   * Compute aggregate performance analytics
   * @returns {Object} Comprehensive performance stats
   */
  computeAnalytics() {
    const closed = this.getClosedTrades();
    if (closed.length === 0) {
      return {
        tradeCount: 0,
        winRatePct: 0,
        totalNetPnlInr: 0,
        profitFactor: 0,
        averageWinInr: 0,
        averageLossInr: 0,
        expectancyInr: 0,
        maxDrawdownPct: 0,
        avgHoldingDays: 0,
        closedTrades: []
      };
    }

    const wins = closed.filter(t => t.net_pnl_inr > 0);
    const losses = closed.filter(t => t.net_pnl_inr <= 0);

    const winCount = wins.length;
    const lossCount = losses.length;
    const winRatePct = (winCount / closed.length) * 100;

    const totalWinPnl = wins.reduce((sum, t) => sum + t.net_pnl_inr, 0);
    const totalLossPnl = Math.abs(losses.reduce((sum, t) => sum + t.net_pnl_inr, 0));
    const totalNetPnlInr = closed.reduce((sum, t) => sum + t.net_pnl_inr, 0);

    const averageWinInr = winCount > 0 ? totalWinPnl / winCount : 0;
    const averageLossInr = lossCount > 0 ? totalLossPnl / lossCount : 0;
    const profitFactor = totalLossPnl > 0 ? totalWinPnl / totalLossPnl : (totalWinPnl > 0 ? Infinity : 0);

    // Expectancy = (P(win) * AvgWin) - (P(loss) * AvgLoss)
    const pWin = winCount / closed.length;
    const pLoss = lossCount / closed.length;
    const expectancyInr = (pWin * averageWinInr) - (pLoss * averageLossInr);

    // Holding days average
    const totalDays = closed.reduce((sum, t) => sum + (t.holding_days ?? 0), 0);
    const avgHoldingDays = closed.length > 0 ? Number((totalDays / closed.length).toFixed(1)) : 0;

    // Maximum drawdown calculation on cumulative P&L
    let peak = 0;
    let maxDrawdownInr = 0;
    let runningPnl = 0;

    for (const trade of closed) {
      runningPnl += trade.net_pnl_inr;
      if (runningPnl > peak) peak = runningPnl;
      const dd = peak - runningPnl;
      if (dd > maxDrawdownInr) maxDrawdownInr = dd;
    }

    return {
      tradeCount: closed.length,
      winCount,
      lossCount,
      winRatePct: Number(winRatePct.toFixed(2)),
      totalNetPnlInr: Number(totalNetPnlInr.toFixed(2)),
      profitFactor: Number(profitFactor.toFixed(2)),
      averageWinInr: Number(averageWinInr.toFixed(2)),
      averageLossInr: Number(averageLossInr.toFixed(2)),
      expectancyInr: Number(expectancyInr.toFixed(2)),
      maxDrawdownInr: Number(maxDrawdownInr.toFixed(2)),
      avgHoldingDays,
      closedTrades: closed
    };
  }

  /**
   * Reconcile trade journal records against live portfolio holdings
   * 
   * @param {Array<Object>} portfolioHoldings - Array of current portfolio holding objects
   * @returns {Object} Reconciliation summary
   */
  reconcileWithPortfolio(portfolioHoldings = []) {
    const activeTrades = this.getActivePositions();
    const discrepancies = [];

    const portfolioMap = new Map();
    for (const h of portfolioHoldings) {
      portfolioMap.set(h.trading_symbol?.toUpperCase() || h.symbol?.toUpperCase(), h);
    }

    for (const trade of activeTrades) {
      const match = portfolioMap.get(trade.symbol.toUpperCase());
      if (!match) {
        discrepancies.push(`Journal trade #${trade.id} for ${trade.symbol} is marked ACTIVE, but was not found in portfolio holdings.`);
      } else if (match.quantity < trade.quantity) {
        discrepancies.push(`Quantity Mismatch: Journal shows ${trade.quantity} shares of ${trade.symbol}, but portfolio holdings show ${match.quantity} shares.`);
      }
    }

    const status = discrepancies.length === 0 ? 'RECONCILED' : 'DISCREPANCIES_DETECTED';

    try {
      const stmt = this.db.prepare(`
        INSERT INTO reconciliations (portfolio_holdings_count, journal_active_count, discrepancies, status)
        VALUES (?, ?, ?, ?)
      `);
      stmt.run(portfolioHoldings.length, activeTrades.length, JSON.stringify(discrepancies), status);
    } catch (_) {}

    return {
      status,
      portfolioHoldingsCount: portfolioHoldings.length,
      holdingsCount: portfolioHoldings.length,
      journalActiveCount: activeTrades.length,
      discrepancies
    };
  }

  /**
   * Gracefully close SQLite database connection
   */
  close() {
    try {
      if (this.db) {
        this.db.close();
      }
    } catch (_) {}
  }
}
