export function getTradingDates(count = 20, refDate = new Date()) {
  const dates = [];
  let d = new Date(refDate);
  const istFormatter = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Kolkata',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit'
  });
  
  while (dates.length < count) {
    const formatted = istFormatter.format(d);
    const day = new Date(formatted + 'T12:00:00Z').getUTCDay();
    // Exclude weekends (Saturday = 6, Sunday = 0)
    if (day !== 0 && day !== 6) {
      dates.push(formatted);
    }
    d.setDate(d.getDate() - 1);
  }
  return dates;
}

